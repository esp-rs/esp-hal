fn read(i2c: &mut I2c<'_, Blocking>, reg: u16) -> Result<u8, Error> {
    let mut value = [0];
    i2c.write_read(ADDRESS, &reg.to_be_bytes(), &mut value)?;
    Ok(value[0])
}

fn write(i2c: &mut I2c<'_, Blocking>, reg: u16, value: u8) -> Result<(), Error> {
    let [high, low] = reg.to_be_bytes();
    i2c.write(ADDRESS, &[high, low, value])
}

pub fn read_id(i2c: &mut I2c<'_, Blocking>) -> Result<u16, Error> {
    Ok(u16::from_be_bytes([
        read(i2c, REG_ID_H)?,
        read(i2c, REG_ID_L)?,
    ]))
}

/// Programs the mode with the stream off.
pub fn configure(i2c: &mut I2c<'_, Blocking>, delay: &Delay) -> Result<(), Error> {
    for &(reg, value) in MODE_1024X600_RAW8_30FPS {
        write(i2c, reg, value)?;
    }
    delay.delay_millis(5);
    Ok(())
}

/// Sets the exposure in lines and the unit gain, entry 0 of the sensor's
/// gain table.
pub fn set_exposure_unit_gain(i2c: &mut I2c<'_, Blocking>, lines: u32) -> Result<(), Error> {
    assert!(
        (1..=MAX_EXPOSURE_LINES).contains(&lines),
        "exposure out of range"
    );
    // The low 4 bits of 0x3e02 are a fraction of a line and stay 0.
    write(i2c, REG_EXPOSURE_H, ((lines >> 12) & 0xf) as u8)?;
    write(i2c, REG_EXPOSURE_M, ((lines >> 4) & 0xff) as u8)?;
    write(i2c, REG_EXPOSURE_L, ((lines & 0xf) << 4) as u8)?;
    write(i2c, REG_DIG_FINE_GAIN, 0x80)?;
    write(i2c, REG_DIG_COARSE_GAIN, 0x00)?;
    write(i2c, REG_ANALOG_GAIN, 0x00)
}

pub fn set_stream(i2c: &mut I2c<'_, Blocking>, on: bool) -> Result<(), Error> {
    write(i2c, REG_STREAM, on as u8)
}
